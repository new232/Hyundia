-- =========================================================
-- [개념] 문자열 연결 함수 및 연산자
-- =========================================================
-- CONCAT()    : 여러 값을 문자열로 변환하여 하나로 연결하는 함수
-- CONCAT_WS() : 지정한 구분자를 사이에 넣어 값을 연결하는 함수
-- ||          : 두 문자열을 연결하는 SQL 연산자
--
-- 기본 문법
-- CONCAT(값1, 값2, ...)
-- CONCAT_WS(구분자, 값1, 값2, ...)
-- 문자열1 || 문자열2
--
-- 예) CONCAT('설비-', 'M14860')
-- 결과: 설비-M14860
--
-- 예) CONCAT_WS('-', '설비', 'M14860', 'H')
-- 결과: 설비-M14860-H
--
-- ※ CONCAT과 CONCAT_WS는 NULL 인수를 무시한다.
--    단, CONCAT_WS의 구분자가 NULL이면 결과는 NULL이다.
-- ※ || 연산은 피연산자 중 NULL이 있으면 NULL을 반환한다.
   
-- [실습 5] 문자열 연결
-- 문제: 여러 문자열을 하나로 합치시오.

SELECT
    CONCAT('설비-', 'M14860')              AS CONCAT사용,
    '설비-' || 'M14860'                    AS 파이프연산자,
    CONCAT_WS('-', '설비', 'M14860', 'H')  AS 구분자포함;



-- =========================================================
-- [개념] COALESCE - NULL 값 처리
-- =========================================================
-- COALESCE : 여러 표현식 중 첫 번째 NULL이 아닌 값을
--            반환하는 SQL 조건 표현식이다.
--
-- 기본 문법
-- COALESCE(값1, 값2, 값3, ...)
--
-- 동작 원리
-- 1. 왼쪽부터 순서대로 값을 확인한다.
-- 2. NULL이 아닌 첫 번째 값을 반환한다.
-- 3. 모든 값이 NULL이면 NULL을 반환한다.
--
-- 예) COALESCE(NULL, '기본값')
-- 결과: 기본값
--
-- 예) COALESCE(NULL, NULL, '서울')
-- 결과: 서울
--
-- 예) COALESCE('부산', '서울')
-- 결과: 부산
--
-- 예) COALESCE(NULL, NULL)
-- 결과: NULL
--
-- ※ 주요 활용
--   - NULL을 기본값으로 대체
--   - 조회 결과에서 누락된 값을 표시
--   - 계산 과정에서 NULL 처리
-- [실습 6] NULL 연결 주의
-- 문제: NULL이 포함된 연결 결과를 확인하시오.

SELECT
    CONCAT('A', NULL, 'B')     AS CONCAT결과,   -- AB
    'A' || NULL || 'B'         AS 파이프결과,   -- NULL
    'A' || COALESCE(NULL, '') || 'B' AS 안전한연결;  -- AB

-- ※ || 사용 시 NULL 주의
--   컬럼에 NULL이 있으면 전체가 NULL이 된다.
--   COALESCE로 감싸면 안전하다.



