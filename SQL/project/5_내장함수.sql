-- pg_typeof() : 표현식 또는 값의 PostgreSQL 자료형을 확인하는 함수

SELECT
    DATE_TRUNC('month', DATE '2025-03-15')            AS date입력,
    pg_typeof(DATE_TRUNC('month', DATE '2025-03-15')) AS 반환타입,   -- timestamp with time zone
    DATE_TRUNC('month', DATE '2025-03-15')::DATE      AS 날짜만;
--
-- ※ 사용 예
--   월별 집계  → GROUP BY DATE_TRUNC('month', 날짜)
