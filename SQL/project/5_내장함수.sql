-- [실습 15] 현재 날짜와 시간
-- 문제: 현재 날짜와 시간을 조회하시오.

SELECT
    CURRENT_DATE                AS 오늘날짜,
    CURRENT_TIME                AS 현재시간,
    CURRENT_TIMESTAMP           AS 현재일시,
    NOW()                       AS NOW결과,
    LOCALTIMESTAMP              AS 로컬일시;

-- ※ CURRENT_TIMESTAMP와 NOW()는 같다.
--   NOW()가 더 짧아서 자주 쓴다.

-- ※ 결과 읽는 법
--   오늘날짜 : 2026-08-04                        DATE
--   현재시간 : 21:03:11.823231+09:00             TIME WITH TIME ZONE
--   현재일시 : 2026-08-04 21:03:11.823231+09     TIMESTAMP WITH TIME ZONE
--   NOW결과  : 2026-08-04 21:03:11.823231+09     TIMESTAMP WITH TIME ZONE
--   로컬일시 : 2026-08-04 21:03:11.823231        TIMESTAMP (시간대 없음)
--
--   세션 TimeZone이 Asia/Seoul이면 +09로 보인다.
--   TIMESTAMP WITH TIME ZONE 값은 내부적으로 UTC 기준 시점으로 저장
--  UTC(Coordinated Universal Time, 협정 세계시): 전 세계에서 날짜와 시간을 일관되게 표현하기 위해 사용하는 국제 표준 시간 기준이다. 
--
--  한국은 UTC보다 9시간 빠르므로 KST(한국 표준시) = UTC + 9시간
--  UTC 기준 시간	한국 시간(KST)
--  2026-10-13 00:00	2026-10-13 09:00
   
-- 현재 세션 시간대 확인
SHOW TimeZone;
--
-- ※ .823231은 마이크로초다
--   초 아래 소수점 6자리까지 기본으로 표시된다.
--   초까지만 필요하면 CURRENT_TIMESTAMP(0) 또는 TO_CHAR를 쓴다.
 
SELECT
    CURRENT_TIMESTAMP(0)                      AS 초단위까지,
    TO_CHAR(NOW(), 'YYYY-MM-DD HH24:MI:SS')   AS 형식지정;
 

--
-- ※ 상황별 선택
--   날짜만              → CURRENT_DATE
--   시간대 포함 현재 시각 → NOW()
--   시간대 없는 현재 시각 → LOCALTIMESTAMP

-- [실습 16] DATE_TRUNC - 날짜 자르기
-- 문제: 날짜를 원하는 단위로 자르시오.

SELECT
    '2025-03-15 14:30:45'::TIMESTAMP                    AS 원본,
    DATE_TRUNC('hour',    '2025-03-15 14:30:45'::TIMESTAMP) AS 시간단위,
    DATE_TRUNC('day',     '2025-03-15 14:30:45'::TIMESTAMP) AS 일단위,
    DATE_TRUNC('week',    '2025-03-15 14:30:45'::TIMESTAMP) AS 주단위,
    DATE_TRUNC('month',   '2025-03-15 14:30:45'::TIMESTAMP) AS 월단위,
    DATE_TRUNC('quarter', '2025-03-15 14:30:45'::TIMESTAMP) AS 분기단위,
    DATE_TRUNC('year',    '2025-03-15 14:30:45'::TIMESTAMP) AS 년단위;

-- ※ DATE_TRUNC는 지정 단위 아래를 모두 0으로 만든다.
--   월 단위로 자르면 그 달의 1일 0시가 된다.
--
-- ※ week 단위는 월요일 기준이다.


-- [실습 17] EXTRACT - 날짜 정보 추출
-- 문제: 날짜에서 특정 값을 숫자로 꺼내시오.

SELECT
    '2025-03-15'::DATE                      AS 원본,
    EXTRACT(YEAR    FROM '2025-03-15'::DATE) AS 년,
