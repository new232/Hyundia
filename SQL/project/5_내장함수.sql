-- FM을 붙이지 않으면 앞에 공백이 생긴다. 문자열로 이어 붙일 때 문제가 되므로 보통 붙인다. 
-- 형식 자리보다 큰 숫자가 들어오면 #으로 표시되므로 자리를 넉넉하게 잡는다.
-- ※ 형식 문자
--   9 : 숫자 자리 (값이 없으면 공백)
--   0 : 숫자 자리 (값이 없으면 0)
--   , : 천 단위 구분자
--   . : 소수점
 
 
-- [실습 30] 자리가 부족하면 #이 나온다
-- 문제: 형식 자리보다 큰 숫자를 넣으면 어떻게 되는지 확인하시오.
 
SELECT
    TO_CHAR(1234.5678, 'FM999.99')   AS 자리부족,   -- ###.##
    TO_CHAR(1234.5678, 'FM9999.99')  AS 자리충분;   -- 1234.57
 
-- ※ ###.##의 의미
--   'FM999.99'는 정수부 자리가 9 세 개, 즉 3자리까지만 허용한다.
--   1234는 정수부가 4자리라서 형식에 들어가지 못한다.
--   자리가 부족하면 오류 대신 결과 전체가 #으로 표시된다.
--
-- ※ 컬럼별 정상/부족 비교
--   FM999,999,999 에 1234567 → 정수부 9자리 제공, 7자리 입력 → 정상
--   FM999.99      에 1234.57 → 정수부 3자리 제공, 4자리 입력 → ###.##
--   FM990.99      에 0.15    → 정수부 3자리 제공, 1자리 입력 → 정상
--
-- ※ 결론: 정수부 자리는 넉넉하게 잡는다.
--   소수 부분은 지정한 자리에서 반올림된다. (1234.5678 → 1234.57)


