-- [실습 11] 반올림, 올림, 내림
-- 문제: 소수점 처리 함수를 비교하시오.

SELECT
    3.7                    AS 원본,
    ROUND(3.7)             AS 반올림,      -- 4
    CEIL(3.2)              AS 올림,        -- 4
    FLOOR(3.9)             AS 내림,        -- 3
    TRUNC(3.9)             AS 버림;        -- 3

-- ※ FLOOR vs TRUNC (음수에서 다르다)
SELECT
    FLOOR(-3.5)  AS FLOOR결과,   -- -4 (더 작은 쪽)
    TRUNC(-3.5)  AS TRUNC결과;   -- -3 (소수점만 버림)


