-- =========================================================
-- [개념] 문자열 함수
-- =========================================================
-- 문자열을 자르고 붙이고 바꾸는 함수들이다.
-- 데이터 정제 작업에서 매우 자주 쓴다.
--
-- ※ PostgreSQL 문자열 인덱스는 1부터 시작한다
--   많은 프로그래밍 언어가 0부터 시작하는 것과 다르다.
-- =========================================================
-- =========================================================
-- [개념] 주요 문자열 함수
-- =========================================================
-- UPPER()     : 문자열을 대문자로 변환
-- LOWER()     : 문자열을 소문자로 변환
-- INITCAP()   : 각 단어의 첫 글자를 대문자로 변환
-- LENGTH()    : 문자열의 문자 개수 반환
-- TRIM()      : 문자열 양쪽 끝의 공백 제거
-- LTRIM()     : 문자열 왼쪽 공백 제거
-- RTRIM()     : 문자열 오른쪽 공백 제거
--
-- ※ TRIM 계열은 기본적으로 지정한 방향의
--    양 끝 공백을 제거하며, 중간 공백은 유지한다.
-- =========================================================

-- [실습 1] 대소문자 변환
-- 문제: 문자열의 대소문자를 바꾸시오.

SELECT
    'Hello World'              AS 원본,
    UPPER('Hello World')       AS 대문자,
    LOWER('Hello World')       AS 소문자,
    INITCAP('hello world')     AS 첫글자대문자;

-- ※ INITCAP은 각 단어의 첫 글자만 대문자로 만든다.
--   이름이나 제목 정리에 유용하다.


-- [실습 2] 길이와 공백 처리
-- 문제: 문자열 길이를 구하고 공백을 제거하시오.

SELECT
    LENGTH('M14860')            AS 길이,
    LENGTH('  M14860  ')        AS 공백포함길이,
    TRIM('  M14860  ')          AS 양쪽공백제거,
    LTRIM('  M14860  ')         AS 왼쪽공백제거,
    RTRIM('  M14860  ')         AS 오른쪽공백제거,
    LENGTH(TRIM('  M14860  '))  AS 제거후길이;



-- =========================================================
-- [개념] 문자열 추출 함수
-- =========================================================
-- SUBSTRING() : 문자열에서 지정한 위치부터
--               원하는 길이만큼 문자를 추출하는 함수
-- LEFT()      : 문자열의 왼쪽부터 지정한 개수의 문자를 추출
-- RIGHT()     : 문자열의 오른쪽부터 지정한 개수의 문자를 추출
--
-- 기본 문법
-- SUBSTRING(문자열, 시작위치, 길이)
-- LEFT(문자열, 개수)
-- RIGHT(문자열, 개수)
--
-- ※ PostgreSQL의 문자열 위치는 1부터 시작한다.
-- ※ SUBSTRING(문자열, 시작위치, 길이)
--   길이를 생략하면 끝까지 가져온다.
-- =========================================================
-- [실습 3] 문자열 자르기
-- 문제: 문자열의 일부를 추출하시오.

SELECT
    'M14860'                        AS 원본,
    SUBSTRING('M14860', 1, 1)       AS 첫글자,
    SUBSTRING('M14860', 2)          AS 두번째부터끝까지,
    SUBSTRING('M14860', 2, 3)       AS 두번째부터3글자,
    LEFT('M14860', 3)               AS 왼쪽3글자,
    RIGHT('M14860', 3)              AS 오른쪽3글자;



