-- [실습 29] 숫자 형식 변환
-- 문제: 숫자에 천 단위 구분자를 넣으시오.

SELECT
    1234567                              AS 원본,
    TO_CHAR(1234567, 'FM999,999,999')     AS 천단위구분,
    TO_CHAR(1234.5678, 'FM9999.99')        AS 소수점2자리,
    TO_CHAR(0.15, 'FM990.99')             AS 앞자리0표시;

-- ※ FM은 앞뒤 공백을 제거하는 옵션이다.
