    EXTRACT(MONTH FROM '2025-03-15'::DATE)                AS EXTRACT결과;      -- 3

-- ※ 차이
--   DATE_TRUNC : timestamp 반환 → 기간별 집계에 사용
--   EXTRACT    : 숫자 반환       → 특정 값 필터링에 사용
--
-- ※ 확인하기: DATE_TRUNC 반환 타입
--   timestamp 입력                → timestamp 반환
--   timestamp with time zone 입력 → timestamp with time zone 반환
--   interval 입력                 → interval 반환
--   date 입력은 공식 문서에 timestamp로 자동 변환된다고 적혀 있지만,
--   실제로 실행하면 timestamp with time zone으로 반환되어 +09 같은 시간대가 붙는다.
--   날짜만 필요하면 결과에 ::DATE를 붙이고,
--   시간대 없는 timestamp가 필요하면 입력에 ::TIMESTAMP를 붙인다.
--
