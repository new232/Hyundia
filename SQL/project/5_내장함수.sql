-- [실습 8] CAST 두 가지 문법
-- 문제: 같은 변환을 두 방법으로 하시오.

SELECT
    CAST('2025-01-01' AS DATE)     AS 표준문법,
    '2025-01-01'::DATE             AS PG문법,
